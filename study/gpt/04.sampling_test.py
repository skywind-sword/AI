def main():
    """
    [전체 실행 흐름]

    1. Temperature별 Sampling 옵션 선택
    2. 각 설정으로 동일한 질문을 3회 반복
    3. Ollama REST API로 답변 생성
    4. 생성된 답변과 실행정보 출력
    5. 결과를 리스트에 저장
    6. 전체 실험 결과를 표로 출력

    [실험 구성]

    Temperature:
        0.0 / 0.5 / 1.0 / 1.5

    각 Temperature별 반복:
        3회

    총 실행 횟수:
        4개 설정 × 3회 = 12회

    Top-p:
        전체 실험에서 1.0으로 고정

    Seed:
        지정하지 않음
    """

    # 전체 실험 결과를 저장할 리스트
    #
    # 각 실행 결과를 Dictionary로 저장한다.
    # 마지막에 전체 결과를 요약하는 데 사용한다.
    results = []

    # --------------------------------------------------------
    # STEP 1. Temperature별 실험 반복
    # --------------------------------------------------------

    # SETTINGS의 각 항목을 차례로 가져온다.
    #
    # 예:
    # options = {
    #     "temperature": 0.5,
    #     "top_p": 1.0
    # }
    for options in SETTINGS:

        # ----------------------------------------------------
        # STEP 2. 동일 조건으로 3회 반복
        # ----------------------------------------------------

        # range(1, REPEAT_COUNT + 1)
        #
        # REPEAT_COUNT가 3이면
        # 1, 2, 3 순서로 반복한다.
        #
        # 동일한 설정에서도 Sampling 결과가
        # 달라지는지 관찰하기 위한 반복이다.
        for repeat in range(1, REPEAT_COUNT + 1):

            print(f"\n{'=' * 65}")

            print(
                f"Temperature={options['temperature']}, "
                f"Top-p={options['top_p']}, "
                f"반복={repeat}"
            )

            print("=" * 65)

            # ------------------------------------------------
            # STEP 3. LLM 답변 생성
            # ------------------------------------------------

            # generate_answer() 내부에서:
            #
            # 1. REST API 요청
            # 2. Gemma 3 4B 추론
            # 3. 생성 결과 수신
            # 4. 토큰 수 및 실행시간 추출
            #
            # 과정을 수행한다.
            result = generate_answer(options)

            # ------------------------------------------------
            # STEP 4. 개별 실행 결과 출력
            # ------------------------------------------------

            print(result["answer"])

            print(
                f"\n출력 토큰: {result['tokens']}"
            )

            print(
                f"전체 소요 시간: "
                f"{result['elapsed']:.2f}초"
            )

            print(
                f"토큰 평가 시간: "
                f"{result['seconds']:.2f}초"
            )

            print(
                f"종료 사유: {result['done_reason']}"
            )

            # ------------------------------------------------
            # STEP 5. 실험 결과 저장
            # ------------------------------------------------

            # 기존 결과에 실험 설정을 추가한다.
            #
            # **options:
            # Temperature와 Top-p 값을 펼쳐서 추가한다.
            #
            # result:
            # generate_answer()에서 반환된 결과
            #
            # 하나의 Dictionary로 합쳐 리스트에 저장한다.
            results.append({
                **options,
                **result
            })

    # --------------------------------------------------------
    # STEP 6. 전체 실험 결과 요약
    # --------------------------------------------------------

    # 저장된 모든 실험 결과를 표 형태로 출력한다.
    print_summary(results)


