#
# [LLM의 답변 생성 원리]
#
# 생성형 LLM은 질문 전체에 대한 답변을 한 번에
# 생성하는 것이 아니다.
#
# 앞서 입력된 토큰과 이미 생성한 토큰을 참고하여
# 다음에 올 토큰의 확률 분포를 계산한다.
#
# 예를 들어 다음 토큰의 확률이 다음과 같다고 가정한다.
#
# "은행" : 50%
# "금융" : 30%
# "고객" : 15%
# "기타" :  5%
#
# 모델은 Sampling 설정에 따라 다음 토큰을 선택한다.
# 선택된 토큰은 다시 입력 문맥에 추가되고,
# 다음 토큰을 예측하는 과정이 반복된다.
#
# 이렇게 토큰을 순차적으로 생성하여 답변이 완성된다.
#
# 위 확률은 개념 설명을 위한 가상의 예시이다.
#
# ------------------------------------------------------------
# [Temperature란?]
#
# Temperature는 다음 토큰의 확률 분포를 조정하는
# 생성 옵션이다.
#
# Temperature가 낮을수록:
#   - 높은 확률의 토큰을 선택하는 경향이 강해진다.
#   - 답변의 다양성이 줄어들 수 있다.
#   - 일관된 답변 생성에 유리할 수 있다.
#
# Temperature가 높을수록:
#   - 낮은 확률의 토큰도 선택될 가능성이 커진다.
#   - 다양한 표현과 아이디어를 생성할 수 있다.
#   - 부정확하거나 불안정한 답변이 증가할 수 있다.
#
# [이번 실습의 설정]
#
# Temperature = 0.0
#   - 일반적으로 Greedy Decoding에 가까운 동작
#   - 확률이 가장 높은 토큰을 선택하는 방식
#
# Temperature = 0.5
#   - 비교적 보수적인 생성
#
# Temperature = 1.0
#   - 모델의 원래 확률 분포를 기준으로 샘플링
#
# Temperature = 1.5
#   - 확률 분포를 더 평탄하게 만들어
#     상대적으로 다양한 토큰이 선택될 수 있음
#
# 주의:
# Temperature가 0이어도 실행 환경이나 연산 차이로
# 결과의 완전한 재현성이 보장되지는 않는다.
#
# 또한 Temperature가 높다고 해서
# 답변의 품질이나 창의성이 반드시 높아지는 것은 아니다.
#
# ------------------------------------------------------------
# [Top-p란? - Nucleus Sampling]
#
# Top-p는 확률이 높은 토큰부터 누적하여
# 일정 확률에 도달하는 후보 집합을 만드는 방식이다.
#
# 예를 들어 다음 토큰의 확률이 다음과 같다고 가정한다.
#
# 토큰 A : 40%
# 토큰 B : 30%
# 토큰 C : 20%
# 토큰 D : 10%
#
# Top-p = 0.7
#
# 확률이 높은 순서대로 누적하면
# A(40%) + B(30%) = 70%
#
# 따라서 A와 B를 샘플링 후보로 사용할 수 있다.
#
# Top-p = 0.9라면
# A + B + C까지 후보에 포함된다.
#
# Top-p = 1.0이라면
# 누적 확률에 의한 후보 제한이 사실상 없어진다.
#
# 단, 실제 후보 토큰은 Top-k 등
# 다른 Sampling 옵션에도 영향을 받을 수 있다.
#
# ------------------------------------------------------------
# [Temperature와 Top-p의 차이]
#
# Temperature:
#   토큰 확률 분포의 모양을 조정한다.
#
# Top-p:
#   확률이 높은 토큰들의 누적 확률을 기준으로
#   샘플링 후보 집합을 제한한다.
#
# 두 옵션은 서로 다른 역할을 하며 함께 적용할 수 있다.
#
# ------------------------------------------------------------
# [Seed란?]
#
# Seed는 무작위 샘플링에서 사용하는
# 난수 생성기의 초기값이다.
#
# 같은 모델, 입력, 설정, 실행 환경에서
# Seed를 동일하게 지정하면
# 결과의 재현성을 높일 수 있다.
#
# 하지만 실행 환경 및 연산의 비결정성 때문에
# 완전히 동일한 결과가 항상 보장되지는 않는다.
#
# 이번 실습은 반복 실행 시 답변의 다양성을
# 관찰하는 것이 목적이므로 Seed를 지정하지 않는다.
#
# ------------------------------------------------------------
# [이번 실습에서 주의할 사항]
#
# 1. 동일한 Prompt를 사용한다.
# 2. Temperature별로 각각 3회 반복한다.
# 3. Top-p는 1.0으로 고정한다.
# 4. Seed는 설정하지 않는다.
# 5. 생성된 답변과 토큰 처리속도를 비교한다.
#
# 단, Top-k 등 다른 옵션은 모델/서버의 기본값을 따른다.
# 따라서 Temperature 이외의 모든 조건이
# 수학적으로 완전히 동일하다고 보장되는 것은 아니다.
