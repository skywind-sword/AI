# 5. 실험 결과 요약 출력 함수
# ============================================================

def print_summary(results):
    """
    [목적]
    모든 Sampling 실험 결과를 표 형태로 출력한다.

    [매개변수]
    results : list[dict]
        각 실험에서 생성한 결과 목록

    [출력 항목]
    TEMP    : Temperature
    TOP-P   : Top-p
    TOKENS  : 출력 토큰 수
    TOK/S   : 초당 출력 토큰 수
    REASON  : 생성 종료 사유

    [토큰 생성속도 계산]

    Tokens/sec = 출력 토큰 수 / 출력 토큰 평가시간

    예:
    출력 토큰 수       = 300
    출력 토큰 평가시간 = 25초

    Tokens/sec = 300 / 25 = 12

    즉, 초당 약 12개의 토큰을 생성한 것이다.
    """

    print("\n========== 실험 결과 요약 ==========")

    # 출력 항목의 폭을 맞추기 위한 포맷 지정
    #
    # >6  : 오른쪽 정렬, 최소 6칸
    # >7  : 오른쪽 정렬, 최소 7칸
    #
    # 문자열 포맷을 이용해 표 형태로 출력한다.
    print(
        f"{'TEMP':>6} "
        f"{'TOP-P':>7} "
        f"{'TOKENS':>8} "
        f"{'TOK/S':>9} "
        f"{'REASON':>10}"
    )

    # 각 실험 결과를 순서대로 처리한다.
    for r in results:

        # ----------------------------------------------------
        # STEP 1. 초당 생성 토큰 수 계산
        # ----------------------------------------------------

        # ZeroDivisionError 방지:
        # 생성 시간이 0이면 계산하지 않고 0을 사용한다.
        speed = (
            r["tokens"] / r["seconds"]
            if r["seconds"] else 0
        )

        # ----------------------------------------------------
        # STEP 2. 실험 결과 출력
        # ----------------------------------------------------

        # f-string 출력 형식:
        #
        # :>6.1f
        #   최소 6칸, 오른쪽 정렬, 소수점 1자리
        #
        # :>9.2f
        #   최소 9칸, 오른쪽 정렬, 소수점 2자리
        print(
            f"{r['temperature']:>6.1f} "
            f"{r['top_p']:>7.1f} "
            f"{r['tokens']:>8} "
            f"{speed:>9.2f} "
            f"{str(r['done_reason']):>10}"
        )


