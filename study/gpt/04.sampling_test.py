# 4. LLM 답변 생성 함수
# ============================================================

def generate_answer(options):
    """
    [목적]
    Ollama REST API를 호출하여 LLM 답변을 생성하고,
    생성 결과와 실행시간 관련 정보를 반환한다.

    [매개변수]
    options : dict
        Sampling 옵션

        예:
        {
            "temperature": 0.5,
            "top_p": 1.0
        }

    [반환값]
    dict
        다음 정보를 포함한다.

        answer         : LLM이 생성한 답변
        tokens         : 출력 토큰 수
        seconds        : 순수 출력 토큰 평가시간(초)
        elapsed        : 전체 API 요청 경과시간(초)
        done_reason    : 생성 종료 사유

    [참고]
    seconds와 elapsed는 서로 다른 시간이다.

    elapsed:
        Python에서 API 호출 전후로 측정한 전체 시간

    seconds:
        Ollama가 반환한 출력 토큰 평가시간

    출력 토큰 생성속도 계산에는
    seconds 값을 사용한다.
    """

    # --------------------------------------------------------
    # STEP 1. REST API 요청 데이터 생성
    # --------------------------------------------------------

    # model:
    # 사용할 Ollama 모델명
    #
    # prompt:
    # LLM에 전달할 사용자 질문
    #
    # stream=False:
    # 토큰을 조금씩 받지 않고 생성 완료 후
    # 하나의 JSON 응답으로 수신한다.
    #
    # options:
    # Temperature, Top-p 등의 생성 옵션을 설정한다.

    payload = {
        "model": MODEL,
        "prompt": PROMPT,
        "stream": False,
        "options": {
            **options,
            "num_predict": NUM_PREDICT

            # Seed를 지정하지 않았기 때문에
            # 매번 Sampling 결과가 달라질 수 있다.
            #
            # 재현성 실험 시에는 다음과 같이
            # Seed를 추가할 수 있다.
            #
            # "seed": 42
        }
    }

    # Python 문법:
    # **options는 Dictionary Unpacking이다.
    #
    # 예:
    # options = {
    #     "temperature": 0.5,
    #     "top_p": 1.0
    # }
    #
    # {
    #     **options,
    #     "num_predict": 400
    # }
    #
    # 결과:
    # {
    #     "temperature": 0.5,
    #     "top_p": 1.0,
    #     "num_predict": 400
    # }
    #
    # 동일한 키가 여러 번 있으면
    # 뒤에서 정의한 값이 앞의 값을 덮어쓴다.

    # --------------------------------------------------------
    # STEP 2. 전체 요청시간 측정 시작
    # --------------------------------------------------------

    # perf_counter()는 경과시간을 측정하는 타이머이다.
    #
    # 이 시점부터 API 호출, 모델 처리, 응답 수신까지
    # 걸리는 시간을 측정한다.
    start = time.perf_counter()

    # --------------------------------------------------------
    # STEP 3. Ollama REST API 호출
    # --------------------------------------------------------

    # requests.post()는 HTTP POST 요청을 전송한다.
    #
    # json=payload:
    # Python dict를 JSON으로 직렬화하여 전송한다.
    #
    # timeout=300:
    # 연결 및 응답 대기에 적용할 제한시간(초)
    # 전체 실행시간을 반드시 300초로 제한한다는
    # 의미는 아니다.
    response = requests.post(
        URL,
        json=payload,
        timeout=300
    )

    # HTTP 오류 상태 확인
    #
    # 400, 404, 500 등 오류 응답이면
    # 예외(Exception)를 발생시킨다.
    response.raise_for_status()

    # --------------------------------------------------------
    # STEP 4. JSON 응답 수신 및 시간 측정 종료
    # --------------------------------------------------------

    # response.json()은 Ollama가 반환한 JSON을
    # Python dict 객체로 변환한다.
    data = response.json()

    # 전체 API 호출 경과시간 계산
    elapsed = time.perf_counter() - start

    # --------------------------------------------------------
    # STEP 5. Ollama 응답 정보 추출
    # --------------------------------------------------------

    # response:
    # LLM이 생성한 최종 텍스트
    #
    # get("response", ""):
    # response 키가 없으면 빈 문자열을 반환한다.
    answer = data.get("response", "")

    # eval_count:
    # Ollama가 보고한 생성 단계의 토큰 수
    #
    # 일반적으로 출력 토큰 수를 의미한다.
    #
    # 토큰은 단어와 반드시 일치하지 않는다.
    # 한국어 문장 하나도 여러 토큰으로 분리될 수 있다.
    output_tokens = data.get("eval_count", 0)

    # eval_duration:
    # 생성 단계에서 토큰을 평가한 시간
    #
    # Ollama는 시간을 나노초(ns) 단위로 반환한다.
    #
    # 1초 = 1,000,000,000나노초
    #
    # 따라서 1e9로 나누어 초 단위로 변환한다.
    generation_sec = (
        data.get("eval_duration", 0) / 1e9
    )

    # done_reason:
    # LLM이 답변 생성을 종료한 이유
    #
    # 일반적인 예:
    #
    # "stop":
    #   종료 조건에 도달하여 정상 종료
    #
    # "length":
    #   num_predict 등 길이 제한으로 종료
    #
    # length인 경우 답변이 중간에 잘렸을 수 있다.
    done_reason = data.get("done_reason")

    # --------------------------------------------------------
    # STEP 6. 결과 반환
    # --------------------------------------------------------

    # 함수 호출부에서 사용할 결과를
    # Dictionary 형태로 반환한다.
    return {
        "answer": answer,
        "tokens": output_tokens,
        "seconds": generation_sec,
        "elapsed": elapsed,
        "done_reason": done_reason
    }


