# 6. 메인 프로그램
# ============================================================

def main():
    """
    [전체 실행 흐름]

    1. 입력 토큰 및 Embedding 벡터 준비
    2. Q, K, V 생성
    3. Attention Score 및 Weight 계산
    4. Value의 가중합으로 Attention Output 생성
    5. 중간 계산 결과와 토큰별 참고 비중 출력

    이번 실습의 핵심은 Transformer가 토큰 간
    정보를 결합하는 계산 원리를 이해하는 것이다.
    """

    # 행렬 출력 시 소수점 3자리까지 표시하고
    # 작은 숫자는 가능한 일반 소수 형태로 출력한다.
    np.set_printoptions(
        precision=3,
        suppress=True
    )

    # --------------------------------------------------------
    # STEP 1. Attention 계산
    # --------------------------------------------------------

    result = calculate_attention(X)

    # --------------------------------------------------------
    # STEP 2. 계산 결과 출력
    # --------------------------------------------------------

    print_attention_result(
        TOKENS,
        X,
        result
    )


