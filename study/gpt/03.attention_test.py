# 1. Transformer의 핵심 기술인 Self-Attention 이해
# 2. Query(Q), Key(K), Value(V)의 역할 이해
# 3. 토큰 간 Attention Score 계산 원리 이해
# 4. Softmax를 이용한 Attention Weight 계산
# 5. Attention 결과로 문맥 정보가 결합되는 과정 확인
#
# [Transformer의 기본 처리 흐름]
#
# 입력 문장
#    ↓
# ① Tokenization : 문장을 토큰으로 분할
#    ↓
# ② Embedding    : 토큰을 숫자 벡터로 변환
#    ↓
# ③ Attention    : 토큰 간 관련성을 계산하고 정보 결합
#    ↓
# ④ Transformer  : Attention, FFN 등을 반복 수행
#    ↓
# ⑤ Output       : 다음 토큰의 확률 분포 계산
#    ↓
# ⑥ Sampling     : 확률 분포에서 다음 토큰 선택
#
# [Self-Attention이란?]
#
# 문장 안의 각 토큰이 다른 토큰들을 얼마나
# 참고해야 하는지 계산하는 메커니즘이다.
#
# 예: "나는 사과를 먹었다"
#
# "먹었다"라는 토큰을 처리할 때
# "나는", "사과를" 등의 정보를 참고하여
# 문맥을 반영한 표현을 계산할 수 있다.
#
# [Q, K, V의 역할]
#
# Q(Query) : 현재 토큰이 찾으려는 정보
# K(Key)   : 각 토큰이 제공하는 정보의 검색 기준
# V(Value) : 실제로 결합할 정보
#
# Q와 K의 유사도로 Attention Weight를 계산하고,
# 그 가중치로 V를 결합하여 출력 벡터를 만든다.
#
# [Attention 공식]
#
# Attention(Q,K,V) = softmax(QKᵀ / √d_k) V
#
# QKᵀ :
#   Query와 Key 사이의 내적(관련성 점수)
#
# √d_k :
#   Key 벡터 차원의 제곱근
#   점수의 크기가 지나치게 커지는 현상을 완화
#
# softmax :
#   관련성 점수를 합계가 1인 가중치로 변환
#
# V :
#   계산된 가중치를 이용해 실제 정보를 결합
#
# [실습 단순화]
# - 토큰 3개, 벡터 2차원
# - 실제 학습된 가중치 대신 단위행렬 사용
# - Multi-Head Attention, 위치 정보 등 생략
# - Causal Mask 미적용
#
# 따라서 실제 Gemma 3의 Attention 계산을
# 그대로 재현한 것은 아니며 원리 학습용이다.
# ============================================================


# ============================================================
# 1. 라이브러리 import
# ============================================================

# NumPy는 벡터 및 행렬 연산을 지원하는 라이브러리
# Transformer의 Attention 계산을 단순화해 구현한다.
import numpy as np


# ============================================================
# 2. 입력 토큰 및 Embedding 데이터
# ============================================================

# 실제 LLM에서는 Tokenizer가 문장을 토큰으로 변환한다.
#
# 이번 실습에서는 토큰화 과정을 생략하고
# 이해하기 쉽게 세 부분으로 직접 나누었다.
TOKENS = ["나는", "사과를", "먹었다"]

# 토큰별 입력 Embedding 벡터
#
# 각 행(Row) : 하나의 토큰
# 각 열(Column) : Embedding 벡터의 차원
#
# X.shape = (3, 2)
#   3 : 토큰 개수
#   2 : Embedding 차원
#
# 실제 모델은 학습된 Embedding을 사용하지만,
# 여기서는 계산하기 쉬운 가상의 숫자를 사용한다.
X = np.array([
    [1.0, 0.0],  # 나는
    [0.0, 1.0],  # 사과를
    [1.0, 1.0]   # 먹었다
])


# ============================================================
# 3. Softmax 함수
# ============================================================

def softmax(x):
    """
    [목적]
    Attention Score를 각 토큰의 참고 비중인
    Attention Weight로 변환한다.

    [매개변수]
    x : Attention Score 행렬

    [반환값]
    각 행의 합계가 1인 가중치 행렬

    [Softmax 원리]
    softmax(x_i) = exp(x_i) / sum(exp(x_j))

    예:
    입력 점수 = [2.0, 1.0, 0.0]

    Softmax 결과 ≈ [0.665, 0.245, 0.090]

    점수가 높은 토큰에 더 큰 가중치가 부여된다.

    [수치적 안정성]
    지수함수 exp()는 입력값이 너무 크면
    오버플로가 발생할 수 있다.

    따라서 각 행의 최댓값을 먼저 빼고 계산한다.
    이는 Softmax 결과를 바꾸지 않는다.
    """

    # 각 행의 최댓값을 빼서 안정적으로 지수 계산
    #
    # axis=-1 : 마지막 차원(여기서는 각 행)을 기준
    # keepdims=True : 계산 결과의 차원을 유지
    exp_x = np.exp(
        x - np.max(x, axis=-1, keepdims=True)
    )

    # 각 행의 지수 합계로 나누어 정규화한다.
    # 결과적으로 각 행의 가중치 합계는 1이 된다.
    return exp_x / np.sum(
        exp_x,
        axis=-1,
        keepdims=True
    )


# ============================================================
# 4. Self-Attention 계산 함수
# ============================================================

def calculate_attention(x):
    """
    [목적]
    입력 토큰의 Embedding 벡터를 이용하여
    Self-Attention 계산 전체 과정을 수행한다.

    [매개변수]
    x : 입력 Embedding 행렬 (토큰 수 × 차원)

    [반환값]
    dict
        Q       : Query 행렬
        K       : Key 행렬
        V       : Value 행렬
        scores  : Attention Score
        weights : Attention Weight
        output  : 최종 Attention 출력

    [전체 흐름]
    1. Q, K, V 생성
    2. Query-Key 관련성 점수 계산
    3. √d_k로 점수 스케일 조정
    4. Softmax로 가중치 계산
    5. 가중치와 Value를 곱하여 최종 출력 생성
    """

    # --------------------------------------------------------
    # STEP 1. Q, K, V 생성
    # --------------------------------------------------------

    # 실제 Transformer에서는 서로 다른 학습 가능한
    # 가중치 행렬 W_Q, W_K, W_V를 사용한다.
    #
    # Q = X × W_Q
    # K = X × W_K
    # V = X × W_V
    #
    # 이번 실습은 계산 원리를 쉽게 보기 위해
    # 단위행렬(Identity Matrix)을 사용한다.
    #
    # 단위행렬을 곱하면 원래 벡터 값이 유지되므로
    # 이번 예제에서는 Q = K = V = X가 된다.

    W_Q = np.eye(2)
    W_K = np.eye(2)
    W_V = np.eye(2)

    # @ 연산자는 행렬 곱셈(Matrix Multiplication)
    Q = x @ W_Q
    K = x @ W_K
    V = x @ W_V

    # --------------------------------------------------------
    # STEP 2. Attention Score 계산
    # --------------------------------------------------------

    # d_k는 Key 벡터의 차원이다.
    #
    # K.shape = (3, 2)이므로
    # K.shape[1] = 2
    d_k = K.shape[1]

    # Q @ K.T
    #
    # Q.shape   = (3, 2)
    # K.T.shape = (2, 3)
    #
    # 결과 shape = (3, 3)
    #
    # 각 행은 현재 토큰의 Query를 의미하고,
    # 각 열은 비교 대상 토큰의 Key를 의미한다.
    #
    # 예:
    # scores[0, 1]
    #   → "나는"의 Query와
    #     "사과를"의 Key 사이의 관련성 점수
    #
    # √d_k로 나누는 이유:
    # 벡터 차원이 커지면 내적의 크기도 커질 수 있다.
    # 큰 점수가 Softmax를 지나치게 뾰족하게 만들어
    # 학습을 어렵게 하는 현상을 완화한다.
    scores = (Q @ K.T) / np.sqrt(d_k)

    # --------------------------------------------------------
    # STEP 3. Attention Weight 계산
    # --------------------------------------------------------

    # Softmax를 적용하여 각 토큰이 다른 토큰들을
    # 얼마나 참고할지 가중치를 계산한다.
    #
    # weights.shape = (3, 3)
    #
    # weights[i, j]:
    # i번째 토큰이 j번째 토큰의 Value를
    # 어느 정도 비중으로 참고하는지 나타낸다.
    #
    # 각 행의 합계는 1이다.
    weights = softmax(scores)

    # --------------------------------------------------------
    # STEP 4. Attention Output 계산
    # --------------------------------------------------------

    # Attention Output = Attention Weight × V
    #
    # weights.shape = (3, 3)
    # V.shape       = (3, 2)
    #
    # output.shape  = (3, 2)
    #
    # 각 토큰의 출력 벡터는 모든 Value 벡터를
    # Attention Weight에 따라 가중합한 결과이다.
    #
    # 즉, 각 토큰의 표현에 다른 토큰의 정보가
    # 결합되는 과정이라고 이해하면 된다.
    output = weights @ V

    # --------------------------------------------------------
    # STEP 5. 계산 결과 반환
    # --------------------------------------------------------

    # 중간 계산 결과를 함께 반환하여
    # Q, K, V부터 최종 출력까지 분석할 수 있도록 한다.
    return {
        "Q": Q,
        "K": K,
        "V": V,
        "scores": scores,
        "weights": weights,
        "output": output
    }


# ============================================================
# 5. Attention 결과 출력 함수
# ============================================================

def print_attention_result(tokens, x, result):
    """
    [목적]
    Attention 계산의 중간 결과와 최종 결과를 출력한다.

    특히 Attention Weight를 백분율로 표시하여
    각 토큰이 어떤 토큰을 얼마나 참고하는지 확인한다.
    """

    Q = result["Q"]
    K = result["K"]
    V = result["V"]
    scores = result["scores"]
    weights = result["weights"]
    output = result["output"]

    print("========== 입력 임베딩 ==========")
    print(x)

    print("\n========== Query (Q) ==========")
    print(Q)

    print("\n========== Key (K) ==========")
    print(K)

    print("\n========== Value (V) ==========")
    print(V)

    print("\n========== Attention Score ==========")
    print(scores)

    print("\n========== Attention Weight ==========")
    print(weights)

    print("\n========== Attention Output ==========")
    print(output)

    # --------------------------------------------------------
    # 토큰별 Attention 비중 출력
    # --------------------------------------------------------

    # Attention Weight의 각 행을 백분율로 출력한다.
    #
    # 예:
    # [나는]이 참고하는 토큰
    #   나는   : xx.xx%
    #   사과를 : xx.xx%
    #   먹었다 : xx.xx%
    #
    # 단, 이번 예제의 가중치는 학습된 언어적 관계가
    # 아니라 임의의 입력 벡터에서 계산된 값이다.
    print("\n========== 토큰별 Attention 비중 ==========")

    for i, token in enumerate(tokens):
        print(f"\n[{token}]이 참고하는 토큰")

        for j, target in enumerate(tokens):
            print(
                f"  {target:<6}: {weights[i, j]:.2%}"
            )


